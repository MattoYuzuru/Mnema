package app.mnema.learning.community;

import java.time.Instant;
import java.util.List;
import java.util.Set;
import java.util.UUID;

/**
 * One row of {@code public_deck} (V67) as the readers of the catalogue see it. The search vectors are never read into Java; they are for the database's own predicates.
 *
 * @param topicId a leaf of the topic directory, or null
 * @param parentTopicId its parent, or null
 * @param itemCount materials of the published revision
 * @param exerciseCount exercises of the published revision
 * @param mediaMask bits of {@link CatalogMedia}
 * @param mechanicsMask bits of {@link CatalogMechanic}
 * @param listed the catalogue threshold (generated by the database)
 * @param firstListedAt «Новое»
 * @param contentUpdatedAt «Обновлена»
 * @param projectedRevisionId the published revision whose exercises were scanned, null until the first scan finished
 */
record PublicDeckRow(UUID deckId, String publicCode, UUID ownerId, UUID publishedRevisionId, String title, String description, String topicId, String parentTopicId,
                     String contentLanguage, String targetLanguage, String level, List<String> tags, int itemCount, int exerciseCount, int mediaMask, int mechanicsMask,
                     boolean listed, Instant firstListedAt, Instant contentUpdatedAt, String titleNorm, UUID projectedRevisionId, Instant projectedAt) {
    Set<CatalogMedia> media() { return CatalogMedia.fromMask(mediaMask); }

    Set<CatalogMechanic> mechanics() { return CatalogMechanic.fromMask(mechanicsMask); }
}
